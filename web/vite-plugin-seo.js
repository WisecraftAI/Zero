import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  SEO_IMAGE_PATH,
  SEO_IMAGE_SIZE,
  SITE_NAME,
  resolvePublicOrigin,
  seoForRoute,
} from './src/lib/seo.js';

/**
 * Build-time metadata for the initial public route. React's PageMetadata
 * component replaces these values on every client-side route transition.
 *
 * Two build-time knobs, resolved the same way as `VITE_API_BASE_URL`
 * (shell env, `web/.env`, or a Docker build arg):
 *
 *   VITE_PUBLIC_SITE_URL  Public origin, e.g. `https://zer0.io`. Unset by
 *                         default. Crawlers and social scrapers ignore
 *                         relative URLs, so canonical / og:url / og:image are
 *                         emitted only once this is known.
 *   VITE_SEO_INDEX        `true` to let crawlers index the app. Default is
 *                         `noindex, nofollow` — ZER0 is an authenticated
 *                         operator console, not a public page.
 */

const PUBLIC_DIR = fileURLToPath(new URL('./public/', import.meta.url));

const isTrue = (value) => /^(1|true|yes|on)$/i.test(String(value ?? '').trim());

function robotsTxt(origin, allowIndexing) {
  const lines = ['# Generated by web/vite-plugin-seo.js', 'User-agent: *'];

  if (!allowIndexing) {
    lines.push('Disallow: /');
    return `${lines.join('\n')}\n`;
  }

  // Only the marketing route is public. Everything else is operator or tenant
  // data. `/home` is absent on purpose: nginx 301s it to `/`, and a redirect
  // consolidates ranking signals where a Disallow would discard them.
  lines.push(
    'Disallow: /dashboard',
    'Disallow: /runs',
    'Disallow: /locators',
    'Disallow: /api-keys',
    'Disallow: /agents',
    'Disallow: /integrations',
    'Allow: /'
  );
  if (origin) lines.push('', `Sitemap: ${origin}/sitemap.xml`);
  return `${lines.join('\n')}\n`;
}

/**
 * Structured data for the landing page. Only emitted with a known origin —
 * schema.org URLs must be absolute, and a graph full of relative paths is
 * worse than no graph at all.
 */
function structuredData(origin, description) {
  const json = JSON.stringify({
    '@context': 'https://schema.org',
    '@type': 'SoftwareApplication',
    name: SITE_NAME,
    applicationCategory: 'DeveloperApplication',
    operatingSystem: 'Web browser',
    url: new URL('/', origin).href,
    image: new URL(SEO_IMAGE_PATH, origin).href,
    description,
  });
  // `</script>` inside a JSON string would close the tag early.
  return json.replace(/</g, '\\u003c');
}

function sitemapXml(origin) {
  // Only the shell is publicly meaningful; every other route needs a session.
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    `  <url><loc>${origin}/</loc><changefreq>weekly</changefreq><priority>1.0</priority></url>`,
    '</urlset>',
    '',
  ].join('\n');
}

export function seoPlugin(env = {}) {
  const origin = resolvePublicOrigin(env.VITE_PUBLIC_SITE_URL);
  const allowIndexing = isTrue(env.VITE_SEO_INDEX);
  const home = seoForRoute({ view: 'home' }, allowIndexing);

  return {
    name: 'zero-seo',

    transformIndexHtml(html) {
      const meta = [
        { name: 'description', content: home.description },
        { name: 'robots', content: home.robots },
        { property: 'og:type', content: 'website' },
        { property: 'og:site_name', content: SITE_NAME },
        { property: 'og:title', content: home.title },
        { property: 'og:description', content: home.description },
        { property: 'og:locale', content: 'en' },
        { name: 'twitter:card', content: 'summary' },
        { name: 'twitter:title', content: home.title },
        { name: 'twitter:description', content: home.description },
      ];

      const tags = meta.map((attrs) => ({ tag: 'meta', attrs, injectTo: 'head' }));

      if (origin) {
        const canonical = new URL('/', origin).href;
        const image = new URL(SEO_IMAGE_PATH, origin).href;
        const size = String(SEO_IMAGE_SIZE);
        tags.push(
          { tag: 'link', attrs: { rel: 'canonical', href: canonical }, injectTo: 'head' },
          { tag: 'meta', attrs: { property: 'og:url', content: canonical }, injectTo: 'head' },
          { tag: 'meta', attrs: { property: 'og:image', content: image }, injectTo: 'head' },
          { tag: 'meta', attrs: { property: 'og:image:width', content: size }, injectTo: 'head' },
          { tag: 'meta', attrs: { property: 'og:image:height', content: size }, injectTo: 'head' },
          { tag: 'meta', attrs: { property: 'og:image:alt', content: `${SITE_NAME} logo` }, injectTo: 'head' },
          { tag: 'meta', attrs: { name: 'twitter:image', content: image }, injectTo: 'head' },
          {
            tag: 'script',
            attrs: { type: 'application/ld+json' },
            children: structuredData(origin, home.description),
            injectTo: 'head',
          },
        );
      }

      return { tags };
    },

    generateBundle() {
      // A hand-written web/public/robots.txt wins — it is copied verbatim and
      // emitting here as well would produce two files with the same name.
      if (!fs.existsSync(path.join(PUBLIC_DIR, 'robots.txt'))) {
        this.emitFile({
          type: 'asset',
          fileName: 'robots.txt',
          source: robotsTxt(origin, allowIndexing),
        });
      }

      if (allowIndexing && origin && !fs.existsSync(path.join(PUBLIC_DIR, 'sitemap.xml'))) {
        this.emitFile({ type: 'asset', fileName: 'sitemap.xml', source: sitemapXml(origin) });
      }
    },
  };
}
